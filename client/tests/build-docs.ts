// Regenerates src/lib/docsContent.ts from the markdown sources in src/components/docs/content/*.md.
// Run: cd client && bun tests/build-docs.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dir, "../src/components/docs/content");
const order: { group: string; slugs: string[] }[] = [
  { group: "Getting started", slugs: ["getting-started"] },
  { group: "Diagram syntax", slugs: ["syntax-flowchart", "syntax-architecture", "syntax-sequence", "syntax-erd"] },
  { group: "Workspace", slugs: ["canvas", "ai", "collaboration"] },
  { group: "Developers", slugs: ["api", "mcp", "cli-and-ci", "embedding"] },
  { group: "Reference", slugs: ["shortcuts", "self-hosting"] },
];

const docs: { slug: string; group: string; title: string; summary: string; body: string }[] = [];
for (const g of order) {
  for (const slug of g.slugs) {
    const raw = readFileSync(join(dir, `${slug}.md`), "utf8");
    const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(raw);
    if (!m) throw new Error(`${slug}: missing front matter`);
    const meta: Record<string, string> = {};
    for (const line of (m[1] ?? "").split("\n")) {
      const i = line.indexOf(":");
      if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
    }
    docs.push({ slug, group: g.group, title: meta.title ?? slug, summary: meta.summary ?? "", body: (m[2] ?? "").trim() + "\n" });
  }
}

const out = `// GENERATED by tests/build-docs.ts from src/components/docs/content/*.md. Edit the markdown, then re-run the script.
export interface DocPage {
  slug: string;
  group: string;
  title: string;
  summary: string;
  body: string;
}

export const DOC_GROUPS: string[] = ${JSON.stringify(order.map((o) => o.group))};

export const DOCS: DocPage[] = ${JSON.stringify(docs, null, 2)};

export const docBySlug = (slug: string): DocPage | undefined => DOCS.find((d) => d.slug === slug);
`;
writeFileSync(join(import.meta.dir, "../src/lib/docsContent.ts"), out);
console.log(`wrote ${docs.length} docs`);
